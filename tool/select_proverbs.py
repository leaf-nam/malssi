def main():
    with open(SRC, encoding='utf-8-sig') as f:
        src = {(r['word'], r['target_code']): r
               for r in csv.DictReader(f)}
    by_word = {}
    for (word, _), r in src.items():
        by_word.setdefault(word, r)

    assert len(SELECTIONS) == 100, f'need 100, got {len(SELECTIONS)}'
    words = [w for w, _, _ in SELECTIONS]
    assert len(set(words)) == 100, 'duplicated words in selection'
    missing = [w for w in words if w not in by_word]
    assert not missing, f'not in source: {missing}'

    with open(DST_CSV, 'w', encoding='utf-8', newline='') as f:
        w = csv.DictWriter(f, fieldnames=[
            'word', 'definition', 'theme', 'target_code', 'link', 'reason',
        ])
        w.writeheader()
        for word, theme, reason in SELECTIONS:
            r = by_word[word]
            w.writerow({
                'word': word,
                'definition': r['definition'],
                'theme': theme,
                'target_code': r['target_code'],
                'link': r['link'],
                'reason': reason,
            })

    from collections import Counter
    counts = Counter(t for _, t, _ in SELECTIONS)
    lines = [
        '# 속담 1차 선정 리뷰 (1.0.3용, 100개)',
        '',
        '> 원본: 국립국어원 우리말샘 속담 9,999건 → 키워드 스크리닝 4,236건 →',
        '> 사람 판독 100건 확정. 각 항목의 선정 이유를 적었다.',
        '> 출처 링크는 원본 CSV의 `link`를 유지한다.',
        '',
        '## 테마별 분포',
        '',
    ]
    for t in THEME_KO:
        lines.append(f'- {THEME_KO[t]}(`{t}`): {counts[t]}개')
    lines += ['', '---', '']

    for theme in THEME_KO:
        items = [(w, r) for w, t, r in SELECTIONS if t == theme]
        lines.append(f'## {THEME_KO[theme]} ({len(items)}개)')
        lines.append('')
        for i, (word, reason) in enumerate(items, 1):
            r = by_word[word]
            lines.append(f'### {i}. {word}')
            lines.append('')
            lines.append(f'> {r["definition"]}')
            lines.append('')
            lines.append(f'- 선정 이유: {reason}')
            lines.append(f'- 출처: {r["link"]}')
            lines.append('')
        lines.append('---')
        lines.append('')

    lines.append(EXCLUDED_NOTE)
    with open(DST_MD, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')

    print(f'selected: {len(SELECTIONS)}')
    print(f'  -> {DST_CSV}')
    print(f'  -> {DST_MD}')
    for t in THEME_KO:
        print(f'  {t}: {counts[t]}')


if __name__ == '__main__':
    main()
