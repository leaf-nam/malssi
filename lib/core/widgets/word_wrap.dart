/// 명언 표시용 줄바꿈 도우미 (#177).
///
/// Flutter는 한글을 음절 단위로 줄바꿈해서 `오늘의 씨앗이` 같은 단어가
/// 중간에 끊긴다. 한글·숫자 음절 사이에 단어 결합자(U+2060)를 넣어
/// 공백에서만 넘어가게 한다. 영문·문장부호 사이는 건드리지 않아
/// 기존 줄바꿈과 같고, 복사·검색용 원문은 저장소에서 그대로 둔다.
String keepWordsTogether(String text) {
  return text.replaceAllMapped(
    RegExp(r'(?<=[가-힣0-9])(?=[가-힣0-9])'),
    (_) => '\u2060',
  );
}
